def soma(valor_1, valor_2):
    ''''
        Função para somar dois valores

        Argumentos:
            valor_1(int): Primeiro valor a ser somado
            valor_2(int): Segundo valor a ser somado

        Retorna:
            int: Resultado da soma
    '''
    return valor_1 + valor_2

def subtracao(valor_1, valor_2):
    ''''
        Função para subtrair dois valores

        Argumentos:
            valor_1(int): Primeiro valor a ser subtraido
            valor_2(int): Segundo valor a ser subtraido

        Retorna:
            int: Resultado da subtração
    '''
    return valor_1 - valor_2

def multiplicacao(valor_1, valor_2):
    ''''
        Função para multiplicar dois valores

        Argumentos:
            valor_1(int): Primeiro valor a ser multiplicado
            valor_2(int): Segundo valor a ser multiplicado

        Retorna:
            int: Resultado da multiplicação
    '''
    return valor_1 * valor_2

def divisao(valor_1, valor_2):
    ''''
        Função para dividir dois valores

        Argumentos:
            valor_1(int): Primeiro valor a ser dividido
            valor_2(int): Segundo valor a ser dividido

        Retorna:
            int: Resultado da divisão
    '''
    return valor_1 / valor_2